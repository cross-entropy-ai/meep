#!/bin/bash
# Build, sign with Developer ID, notarize and staple Meep.app. Writes to the output directory:
#   Meep-<version>-macos-arm64.zip   the app (stapled, so it opens offline on first launch)
#   meep.rb                          the Homebrew cask for that zip
#   checksums.txt                    SHA-256 of both (the tap verifies meep.rb against it)
# Runs locally and in .github/workflows/release.yml.
#
# Notarization credentials, either:
#   NOTARY_APPLE_ID, NOTARY_PASSWORD (app-specific), NOTARY_TEAM_ID     (CI)
#   or a keychain profile, NOTARY_PROFILE (default Meep), stored once with
#   xcrun notarytool store-credentials Meep --apple-id <apple-id> --team-id <team-id>
#
# Usage: scripts/release.sh [output-dir]
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="${1:-build/release}"
APP=build/Meep.app
VERSION=$(/usr/libexec/PlistBuddy -c "Print CFBundleShortVersionString" Info.plist)
NAME="Meep-$VERSION-macos-arm64.zip"
REPO=cross-entropy-ai/meep

if [ -n "${NOTARY_APPLE_ID:-}" ]; then
  NOTARY=(--apple-id "$NOTARY_APPLE_ID" --password "$NOTARY_PASSWORD" --team-id "$NOTARY_TEAM_ID")
else
  NOTARY=(--keychain-profile "${NOTARY_PROFILE:-Meep}")
fi

IDENTITY="${SIGN_IDENTITY:-$(security find-identity -v -p codesigning | awk -F'"' '/Developer ID Application/{print $2; exit}')}"
[[ "$IDENTITY" == "Developer ID Application"* ]] || { echo "No Developer ID Application identity" >&2; exit 1; }

SIGN_IDENTITY="$IDENTITY" ./build.sh
codesign --verify --deep --strict "$APP"

mkdir -p "$OUT"
rm -f "$OUT/$NAME"
ditto -c -k --keepParent "$APP" "$OUT/$NAME"
xcrun notarytool submit "$OUT/$NAME" "${NOTARY[@]}" --wait
xcrun stapler staple "$APP"
spctl --assess --type execute -v "$APP"

# Re-zip so the download carries the stapled ticket.
rm -f "$OUT/$NAME"
ditto -c -k --keepParent "$APP" "$OUT/$NAME"
SHA=$(shasum -a 256 "$OUT/$NAME" | cut -d' ' -f1)

cat > "$OUT/meep.rb" <<EOF
# Generated by scripts/release.sh in $REPO. Do not edit manually.
cask "meep" do
  version "$VERSION"
  sha256 "$SHA"

  url "https://github.com/$REPO/releases/download/v#{version}/Meep-#{version}-macos-arm64.zip"
  name "Meep"
  desc "Menu bar app that records your meetings"
  homepage "https://github.com/$REPO"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on arch: :arm64
  depends_on macos: ">= :sequoia"

  app "Meep.app"
  binary "#{appdir}/Meep.app/Contents/MacOS/Meep", target: "meep"

  uninstall quit: "com.junyi.Meep"

  # Recordings in ~/Documents/MeetingRecordings are left alone.
  zap trash: [
    "~/Library/Application Support/Meep",
    "~/Library/Preferences/com.junyi.Meep.plist",
  ]
end
EOF

(cd "$OUT" && shasum -a 256 "$NAME" meep.rb > checksums.txt)
cat "$OUT/checksums.txt"
