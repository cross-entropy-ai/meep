#!/bin/bash
# Build, sign with Developer ID, notarize and staple Meep.app. Writes to the output directory:
#   Meep-<version>-macos-arm64.zip   the app (stapled, so it opens offline on first launch)
#   meep.rb                          the Homebrew cask for that zip
#   appcast.xml                      the Sparkle feed (SUFeedURL reads it from the latest release)
#   checksums.txt                    SHA-256 of the zip and meep.rb (the tap verifies meep.rb against it)
# Runs locally and in .github/workflows/release.yml.
#
# Sparkle signing key (EdDSA), either:
#   SPARKLE_PRIVATE_KEY (the key exported by generate_keys -x)                  (CI)
#   or the login keychain, account dev.junyi.Meep (generate_keys --account dev.junyi.Meep)
# Release notes for the update window: RELEASE_NOTES (Markdown), optional.
#
# Notarization credentials, either:
#   NOTARY_APPLE_ID, NOTARY_PASSWORD (app-specific), NOTARY_TEAM_ID     (CI)
#   or a keychain profile, NOTARY_PROFILE (default Meep), stored once with
#   xcrun notarytool store-credentials Meep --apple-id <apple-id> --team-id <team-id>
#
# Usage: scripts/release.sh [output-dir]
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="${1:-build/release}"
APP=build/Meep.app
VERSION=$(/usr/libexec/PlistBuddy -c "Print CFBundleShortVersionString" Info.plist)
BUILD=$(/usr/libexec/PlistBuddy -c "Print CFBundleVersion" Info.plist)
MIN_OS=$(/usr/libexec/PlistBuddy -c "Print LSMinimumSystemVersion" Info.plist)
NAME="Meep-$VERSION-macos-arm64.zip"
REPO=cross-entropy-ai/meep

if [ -n "${NOTARY_APPLE_ID:-}" ]; then
  NOTARY=(--apple-id "$NOTARY_APPLE_ID" --password "$NOTARY_PASSWORD" --team-id "$NOTARY_TEAM_ID")
else
  NOTARY=(--keychain-profile "${NOTARY_PROFILE:-Meep}")
fi

IDENTITY="${SIGN_IDENTITY:-$(security find-identity -v -p codesigning | awk -F'"' '/Developer ID Application/{print $2; exit}')}"
[[ "$IDENTITY" == "Developer ID Application"* ]] || { echo "No Developer ID Application identity" >&2; exit 1; }

SIGN_IDENTITY="$IDENTITY" ./build.sh
codesign --verify --deep --strict "$APP"

mkdir -p "$OUT"
rm -f "$OUT/$NAME"
ditto -c -k --keepParent "$APP" "$OUT/$NAME"
xcrun notarytool submit "$OUT/$NAME" "${NOTARY[@]}" --wait
xcrun stapler staple "$APP"
spctl --assess --type execute -v "$APP"

# Re-zip so the download carries the stapled ticket.
rm -f "$OUT/$NAME"
ditto -c -k --keepParent "$APP" "$OUT/$NAME"
SHA=$(shasum -a 256 "$OUT/$NAME" | cut -d' ' -f1)

# Sparkle: sign the zip, then write the feed with this one release.
SIGN_UPDATE=vendor/sparkle/bin/sign_update
if [ -n "${SPARKLE_PRIVATE_KEY:-}" ]; then
  KEY_FILE=$(mktemp)
  printf '%s' "$SPARKLE_PRIVATE_KEY" > "$KEY_FILE"
  ED=$("$SIGN_UPDATE" --ed-key-file "$KEY_FILE" "$OUT/$NAME")
  rm -P "$KEY_FILE"
else
  ED=$("$SIGN_UPDATE" --account dev.junyi.Meep "$OUT/$NAME")
fi
[[ "$ED" == sparkle:edSignature=* ]] || { echo "sign_update failed: $ED" >&2; exit 1; }
NOTES="${RELEASE_NOTES:-}"
NOTES="${NOTES//]]>/]]&gt;}"
cat > "$OUT/appcast.xml" <<APPCAST
<?xml version="1.0" encoding="utf-8"?>
<rss version="2.0" xmlns:sparkle="http://www.andymatuschak.org/xml-namespaces/sparkle">
  <channel>
    <title>Meep</title>
    <link>https://github.com/$REPO</link>
    <item>
      <title>Meep $VERSION</title>
      <pubDate>$(LC_ALL=C date -u "+%a, %d %b %Y %H:%M:%S +0000")</pubDate>
      <sparkle:version>$BUILD</sparkle:version>
      <sparkle:shortVersionString>$VERSION</sparkle:shortVersionString>
      <sparkle:minimumSystemVersion>$MIN_OS</sparkle:minimumSystemVersion>
      <sparkle:fullReleaseNotesLink>https://github.com/$REPO/releases/tag/v$VERSION</sparkle:fullReleaseNotesLink>
      <description sparkle:format="markdown"><![CDATA[$NOTES]]></description>
      <enclosure url="https://github.com/$REPO/releases/download/v$VERSION/$NAME" $ED type="application/octet-stream"/>
    </item>
  </channel>
</rss>
APPCAST

cat > "$OUT/meep.rb" <<EOF
# Generated by scripts/release.sh in $REPO. Do not edit manually.
cask "meep" do
  version "$VERSION"
  sha256 "$SHA"

  url "https://github.com/$REPO/releases/download/v#{version}/Meep-#{version}-macos-arm64.zip"
  name "Meep"
  desc "Menu bar app that records your meetings"
  homepage "https://github.com/$REPO"

  livecheck do
    url :url
    strategy :github_latest
  end

  auto_updates true
  depends_on arch: :arm64
  depends_on macos: :sequoia

  app "Meep.app"
  binary "#{appdir}/Meep.app/Contents/MacOS/Meep", target: "meep"

  uninstall quit: "dev.junyi.Meep"

  # Recordings in ~/Documents/MeepRecordings are left alone.
  zap trash: [
    "~/Library/Application Support/Meep",
    "~/Library/Preferences/dev.junyi.Meep.plist",
    "~/Library/Preferences/com.junyi.Meep.plist",
  ]
end
EOF

(cd "$OUT" && shasum -a 256 "$NAME" meep.rb > checksums.txt)
cat "$OUT/checksums.txt"
